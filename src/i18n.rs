#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CountTextOrder {
    LabelFirst,
    LabelFirstTight,
    CountFirst,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct CountText {
    pub singular: &'static str,
    pub plural: &'static str,
    pub order: CountTextOrder,
}

#[cfg(test)]
impl CountText {
    pub const fn label_first(label: &'static str) -> Self {
        Self {
            singular: label,
            plural: label,
            order: CountTextOrder::LabelFirst,
        }
    }

    pub const fn label_first_tight(label: &'static str) -> Self {
        Self {
            singular: label,
            plural: label,
            order: CountTextOrder::LabelFirstTight,
        }
    }

    pub const fn count_first(singular: &'static str, plural: &'static str) -> Self {
        Self {
            singular,
            plural,
            order: CountTextOrder::CountFirst,
        }
    }
}

impl CountText {
    pub fn label(self, count: usize) -> &'static str {
        if count == 1 {
            self.singular
        } else {
            self.plural
        }
    }
}

